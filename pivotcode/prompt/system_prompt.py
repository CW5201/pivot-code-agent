# ── 技能部分 ────────────────────────────────────────────────────────────────


def get_skills_section(skills: list) -> str:
    """构建系统提示词中的技能列表。

    列出所有发现的技能，包含名称、描述和触发提示，
    以便模型知道它们的存在并可以通过 Skill 工具调用它们。
    """
    if not skills:
        return ""

    lines = [
        "# 可用技能\n",
        "技能是可重用的提示模板。用户通过 `/skill <name> [args]` 调用它们。"
        "你可以通过 Skill 工具调用它们。\n",
    ]
    for skill in skills:
        entry = f"- **{skill.name}**"
        if skill.argument_hint:
            entry += f" {skill.argument_hint}"
        entry += f": {skill.description}"
        if skill.when_to_use:
            entry += f"\n  触发条件：{skill.when_to_use}"
        lines.append(entry)

    return "\n".join(lines)


