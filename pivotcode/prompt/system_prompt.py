"""系统提示词构建模块。

组装 14 个部分的系统提示词（详见 docs/architecture/system-prompt.md）。
静态部分 1-8 设计为跨调用字节相同，以便支持提示词缓存的提供商可以缓存它们；
动态部分 9-14 是每个会话/模式特有的，故意放在缓存链的末尾。
"""

from datetime import UTC, datetime

from pivotcode.utils.env import get_cwd, get_os_version, get_platform, get_shell, is_git_repo

_session_datetime_cache: str | None = None


def get_session_datetime() -> str:
    """返回会话开始时间，首次调用时缓存。

    与模块级常量不同，这对于托管多个会话的长生命周期进程是安全的——
    每次进程重启都会获得新的时间戳。对于真正的多会话进程，请在会话之间
    调用 ``reset_session_datetime()``。
    """
    global _session_datetime_cache
    if _session_datetime_cache is None:
        _session_datetime_cache = datetime.now(UTC).astimezone().strftime("%Y-%m-%d %H:%M")
    return _session_datetime_cache


def reset_session_datetime() -> None:
    """重置缓存的会话日期时间。在长生命周期进程的会话之间调用。"""
    global _session_datetime_cache
    _session_datetime_cache = None


